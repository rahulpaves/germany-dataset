#!/usr/bin/env python3
"""Generate api/data.js with the paid country data inlined.

WHY INLINED. The first version put the data in lib/paid-data.js and had the
function require it. That file sat in the repo root, so Vercel served it as a
static asset and https://germany.pavetheway.ai/lib/paid-data.js returned every
paid record to anyone who asked. The gate was decoration for about four minutes
until a check caught it.

Anything in the repo that is not under api/ can be fetched. Files under api/
are functions, not assets. So the data goes inside the function file itself and
there is no second path to it.

Run after editing any file in data-source/, then commit api/data.js.
Germany is excluded on purpose: it stays free and static in data/.
"""
import json, os, io

FREE = {"germany"}
idx = json.load(open("data/index.json"))
paid = [e["slug"] for e in idx if e["slug"] not in FREE]

store, report = {}, []
for slug in paid:
    src = f"data-source/{slug}.json"
    if not os.path.exists(src):
        raise SystemExit(f"missing {src} — did a paid country get left in data/?")
    store[slug] = {"programmes": json.load(open(src))}
    vp = f"data-source/{slug}-visa.json"
    if os.path.exists(vp):
        store[slug]["visa"] = json.load(open(vp))
    report.append((slug, len(store[slug]["programmes"]), len(store[slug].get("visa", []))))

TEMPLATE = '''/**
 * The gate. GENERATED by build_gate.py — do not edit by hand.
 *
 * Germany is free and served as a static file, exactly as before. The other
 * seven countries leave the server only through here, and only with an access
 * code that matches one we issued.
 *
 * The data is inlined below rather than required from lib/, because anything
 * outside api/ is served as a static asset: the first version of this leaked
 * the whole paid dataset at /lib/paid-data.js. Files under api/ are functions,
 * so this is the only path to the records.
 *
 * Codes live in the ACCESS_CODES environment variable, comma separated. One
 * code per buyer, issued by hand after payment. Adding a buyer is an env var
 * edit, which is the right amount of machinery for a test whose whole purpose
 * is to find out whether anybody buys at all.
 */

const PAID = %s;

const crypto = require('crypto');

const FREE_COUNTRIES = ['germany'];

/* Two ways in, and both are checked here.

   A Stripe token, issued by api/unlock.js after a real payment. It carries its
   own expiry and signature, so this verifies it without a database and without
   calling Stripe again on every fetch.

   A manual code from ACCESS_CODES, for comps, refunds and anyone given access
   by hand. Kept because a test needs a way to let someone in without charging
   them. */

function signingSecret() {
  return process.env.TOKEN_SECRET || process.env.STRIPE_SECRET_KEY || '';
}

function fromB64url(s) {
  return Buffer.from(String(s).replace(/-/g, '+').replace(/_/g, '/'), 'base64');
}

function validToken(token) {
  const secret = signingSecret();
  if (!secret || !token || String(token).indexOf('.') === -1) return false;
  const parts = String(token).split('.');
  if (parts.length !== 2) return false;
  let payload;
  try { payload = fromB64url(parts[0]).toString('utf8'); } catch (e) { return false; }
  const want = crypto.createHmac('sha256', secret).update(payload).digest();
  let got;
  try { got = fromB64url(parts[1]); } catch (e) { return false; }
  // Constant time, so a wrong token cannot be narrowed down by timing it.
  if (want.length !== got.length || !crypto.timingSafeEqual(want, got)) return false;
  const expiresAt = Number(payload.split('|')[1] || 0);
  return Number.isFinite(expiresAt) && Date.now() < expiresAt;
}

function validCode(code) {
  const codes = String(process.env.ACCESS_CODES || '')
    .split(',').map(s => s.trim().toUpperCase()).filter(Boolean);
  if (!codes.length) return false;
  return codes.indexOf(String(code).trim().toUpperCase()) !== -1;
}

function valid(code) {
  if (!code) return false;
  return validToken(code) || validCode(code);
}

module.exports = (req, res) => {
  const url = new URL(req.url, 'http://x');
  const country = String(url.searchParams.get('c') || '').toLowerCase().trim();
  const code = url.searchParams.get('k');
  const part = String(url.searchParams.get('part') || 'programmes').toLowerCase();

  res.setHeader('Content-Type', 'application/json; charset=utf-8');
  // Never cache a gated response at the edge: one buyer's payload must not be
  // handed to the next visitor without a code.
  res.setHeader('Cache-Control', 'no-store, private');

  if (!country) {
    res.statusCode = 400;
    return res.end(JSON.stringify({ error: 'name a country' }));
  }

  if (FREE_COUNTRIES.indexOf(country) !== -1) {
    res.statusCode = 302;
    res.setHeader('Location', '/data/' + country + (part === 'visa' ? '-visa' : '') + '.json');
    return res.end();
  }

  if (!PAID[country]) {
    res.statusCode = 404;
    return res.end(JSON.stringify({ error: 'no such country' }));
  }

  if (!valid(code)) {
    res.statusCode = 402; // Payment Required, which is what this actually is
    return res.end(JSON.stringify({
      error: 'locked',
      country: country,
      message: 'Germany is free. The other seven countries need an access code.',
    }));
  }

  const payload = part === 'visa'
    ? (PAID[country].visa || [])
    : PAID[country].programmes;

  res.statusCode = 200;
  return res.end(JSON.stringify(payload));
};
'''

io.open("api/data.js", "w", encoding="utf-8").write(
    TEMPLATE % json.dumps(store, ensure_ascii=False, separators=(",", ":")))

if os.path.exists("lib/paid-data.js"):
    os.remove("lib/paid-data.js")
    try: os.rmdir("lib")
    except OSError: pass
    print("removed lib/paid-data.js — it was publicly served")

print("api/data.js generated: %d countries, %.1f MB" % (len(store), os.path.getsize("api/data.js")/1e6))
for slug, n, v in report:
    print(f"   {slug:12} {n:3} programmes, {v:2} visa steps")
