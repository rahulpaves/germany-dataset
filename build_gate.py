#!/usr/bin/env python3
"""Rebuild lib/paid-data.js from data-source/.

The paid countries live in data-source/, which .vercelignore keeps out of the
deployment. This inlines them into a module the serverless function bundles, so
the only way to read them in production is through /api/data with a valid code.

Run this after editing any paid country file, then commit lib/paid-data.js.
Germany is deliberately excluded: it stays free and static in data/.
"""
import json, os, io

FREE = {"germany"}
idx = json.load(open("data/index.json"))
paid = [e["slug"] for e in idx if e["slug"] not in FREE]

store, report = {}, []
for slug in paid:
    src = f"data-source/{slug}.json"
    if not os.path.exists(src):
        raise SystemExit(f"missing {src} — did a paid country get left in data/?")
    store[slug] = {"programmes": json.load(open(src))}
    vp = f"data-source/{slug}-visa.json"
    if os.path.exists(vp):
        store[slug]["visa"] = json.load(open(vp))
    report.append((slug, len(store[slug]["programmes"]), len(store[slug].get("visa", []))))

header = (
"/**\n"
" * Paid country data, bundled into the serverless function.\n"
" *\n"
" * GENERATED by build_gate.py from data-source/. Do not edit by hand.\n"
" *\n"
" * The country JSON used to sit in data/ and was fetched straight from the\n"
" * browser, so anyone could open /data/italy.json and take the lot. A gate in\n"
" * the page would have been decoration. These leave the server only through\n"
" * api/data.js, and only with a valid access code.\n"
" *\n"
" * Germany is not in here on purpose. It stays free and public: it is what\n"
" * counsellors already put their hand up for, and it is how a buyer checks the\n"
" * depth before paying for the rest.\n"
" */\n"
)
io.open("lib/paid-data.js", "w", encoding="utf-8").write(
    header + "module.exports = " + json.dumps(store, ensure_ascii=False, separators=(",", ":")) + ";\n")

print("lib/paid-data.js rebuilt: %d countries, %.1f MB" % (len(store), os.path.getsize("lib/paid-data.js")/1e6))
for slug, n, v in report:
    print(f"   {slug:12} {n:3} programmes, {v:2} visa steps")
